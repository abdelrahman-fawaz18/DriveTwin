import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
const control = process.env.EVDT_DASHBOARD_CONTROL;
const fixture = JSON.parse(fs.readFileSync(path.join(control, 'ready.json'), 'utf8'));

test('catalog, actual history, live recovery, scope and responsive layout', async ({ page, context, browser }, info) => {
  const errors = [], external = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.route('**/*', route => {
    if (new URL(route.request().url()).origin !== new URL(fixture.base_url).origin) { external.push(route.request().url()); return route.abort(); }
    return route.continue();
  });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Open a monitoring session' })).toBeVisible();
  await page.getByLabel('Dashboard key').fill(fixture.reader_token);
  await page.getByRole('button', { name: 'Connect to monitoring' }).click();
  await page.getByRole('button', { name: 'Measurements', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Dashboard connected' })).toBeVisible();
  await expect(page.locator('tbody tr[data-signal]')).toHaveCount(24);
  if (!fs.existsSync(path.join(control, 'start-source'))) {
    await expect(page.locator('[data-signal="motion.speed"]')).toContainText('unknown');
    fs.writeFileSync(path.join(control, 'start-source'), '');
  }
  await expect.poll(async () => (await page.locator('[data-signal="motion.speed"]').innerText()).toLowerCase().includes('unknown'), { timeout: 35000 }).toBe(false);
  await page.getByRole('button', { name: 'Measurements', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search measurements' }).fill('battery.pack');
  // Search human signal IDs, including the raw catalog identifier.
  await expect(page.locator('tbody tr[data-signal]')).toHaveCount(6);
  await page.getByRole('textbox', { name: 'Search measurements' }).fill('no-such-signal');
  await expect(page.getByText('No measurements match these filters.')).toBeVisible();
  await page.getByRole('textbox', { name: 'Search measurements' }).fill('');
  await expect(page.locator('tbody tr[data-signal]')).toHaveCount(24);
  await context.setOffline(true);
  await expect(page.getByRole('status').filter({ hasText: 'Disconnected' })).toBeVisible({ timeout: 10000 });
  await expect(page.locator('[data-signal="motion.speed"] .badge.stale')).toBeVisible();
  await context.setOffline(false);
  await expect(page.getByText(/Resynchronized ·/)).toBeVisible({ timeout: 20000 });
  await expect(page.getByRole('status').filter({ hasText: 'Dashboard connected' })).toBeVisible();
  await page.getByRole('button', { name: 'History for motion.speed', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'History', level: 1, exact: true })).toBeVisible();
  await expect(page.getByRole('img', { name: /Motion · Speed history/ })).toBeVisible({ timeout: 15000 });
  await page.getByText('Inspect recorded values and provenance').click();
  await expect(page.locator('.raw tbody tr').first()).toBeVisible();
  await expect(page.getByText('simulated-observation', { exact: true }).first()).toBeVisible();
  await expect.poll(() => fs.existsSync(path.join(control, 'source-finished')), { timeout: 90000 }).toBe(true);
  await page.getByRole('button', { name: 'Use latest time' }).click();
  await page.getByRole('button', { name: 'Apply historical query' }).click();
  await expect(page.locator('.raw tbody tr')).toHaveCount(18, { timeout: 15000 });
  const auth = { Authorization: 'Bearer ' + fixture.reader_token };
  const snap = await (await page.request.get('/v1/snapshot?asset_id=bus-001', { headers: auth })).json();
  expect(snap.run_id).toBe(fixture.run_id);
  const history = await (await page.request.get('/v1/history?' + new URLSearchParams({ asset_id: 'bus-001', signal_id: 'motion.speed', as_of: snap.cursor }), { headers: auth })).json();
  expect(history.items).toHaveLength(18);
  const last = history.items.at(-1);
  const priorTimeText=await page.evaluate(iso=>new Date(iso).toLocaleTimeString('en-US',{hour12:false,timeZone:'UTC'})+' UTC',last.observed_at);
  await expect(page.locator('.raw tbody tr').last()).toContainText(priorTimeText);
  await expect(page.locator('.raw tbody tr').last()).toContainText(new Intl.NumberFormat('en-US', { maximumFractionDigits: 3 }).format(last.sample.value));
  const unauthorized = await page.request.get('/v1/snapshot?asset_id=bus-002', { headers: { Authorization: 'Bearer ' + fixture.scoped_token } });
  expect(unauthorized.status()).toBe(403);
  await page.getByText('Select signals to compare').click();
  await page.getByLabel('Compare battery.pack.power', { exact: true }).check();
  await page.getByRole('button', { name: 'Apply historical query' }).click();
  await expect(page.locator('.chart svg')).toHaveCount(2);
  await page.getByLabel('Shared time cursor').fill('5');
  await expect(page.getByTestId('cursor-reading')).toHaveCount(2);
  for (const signal of ['battery.pack.soc','battery.pack.temperature','battery.pack.current']) await page.getByLabel('Compare '+signal,{exact:true}).check();
  await expect(page.getByLabel('Compare battery.pack.voltage',{exact:true})).toBeEnabled();
  await page.getByLabel('Compare battery.pack.voltage',{exact:true}).check();
  await page.getByRole('button',{name:'Apply historical query'}).click();
  await expect(page.locator('.chart svg')).toHaveCount(6);
  await expect(page.getByTestId('cursor-reading')).toHaveCount(6);
  for (const format of ['JSON','CSV']) {
    const downloaded=page.waitForEvent('download');
    await page.getByRole('button',{name:'Download '+format}).click();
    const download=await downloaded; const file=await download.path(); const text=fs.readFileSync(file,'utf8');
    if(format==='JSON'){const data=JSON.parse(text);expect(data.metadata.run_id).toBe(fixture.run_id);expect(data.metadata.asset_id).toBe('bus-001');expect(data.items).toHaveLength(108);expect(data.metadata.signals['battery.pack.power'].unit).toBe('W');expect(data.metadata.download_complete).toBe(true);}
    else {expect(text).toContain('record_type,metadata_json');expect(text).toContain('metadata,');expect(text.split('\n').filter(l=>l.startsWith('sample,')).length).toBe(108);}
  }
  await page.getByRole('button',{name:'Calculate summary'}).click();
  await expect(page.locator('.summaries tbody tr')).toHaveCount(24);
  let releaseSummary, summaryCaptured=false;
  const heldSummary=async route=>{const response=await route.fetch();summaryCaptured=true;await new Promise(resolve=>{releaseSummary=resolve;});await route.fulfill({response});};
  await page.route('**/v1/history-summary?*',heldSummary);
  await page.getByRole('button',{name:'Calculate summary'}).click();
  await expect.poll(()=>summaryCaptured).toBe(true);
  await page.getByLabel('To working seconds').fill('3');
  await page.getByRole('button',{name:'Apply historical query'}).click();
  releaseSummary();
  await expect(page.getByRole('button',{name:'Calculate summary'})).toBeEnabled();
  await expect(page.locator('.summaries tbody tr')).toHaveCount(0);
  await page.unroute('**/v1/history-summary?*',heldSummary);
  await page.getByRole('button',{name:'Map',exact:true}).click();
  await expect(page.getByTestId('vehicle-position')).toHaveAttribute('aria-label',/stale/);
  await expect(page.getByText(/18 paired observed points/)).toBeVisible();
  await expect(page.locator('[data-map-layer="stations"]')).toHaveCount(2);
  await page.getByLabel('Stops and stations',{exact:true}).uncheck();
  await expect(page.locator('[data-map-layer="stations"]')).toHaveCount(0);
  await page.getByLabel('Stops and stations',{exact:true}).check();
  await expect(page.locator('[data-map-layer="stations"]')).toHaveCount(2);
  const overviewScale=await page.locator('.leaflet-control-scale-line').innerText();
  await page.getByRole('button',{name:'Center on vehicle'}).click();
  await expect(page.locator('.leaflet-control-scale-line')).not.toHaveText(overviewScale);
  await page.getByRole('button',{name:'Fit map',exact:true}).click();
  await expect(page.locator('.leaflet-control-scale-line')).toHaveText(overviewScale);
  await expect(page.locator('.leaflet-zoom-anim')).toHaveCount(0);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(process.env.EVDT_BROWSER_OUTPUT,info.project.name+'-map.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:path.join(process.env.EVDT_BROWSER_OUTPUT,info.project.name+'-map-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1050});
  await page.getByRole('button',{name:'Activity',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Recorded activity'})).toBeVisible();
  await expect(page.getByText('source-state',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Refresh activity'}).click();
  await expect(page.getByText('source-state',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'System',exact:true}).click();
  await expect(page.getByRole('heading',{name:'System health',exact:true})).toBeVisible();
  await expect(page.locator('.cards .metric').first()).toContainText('18');
  await page.screenshot({path:path.join(process.env.EVDT_BROWSER_OUTPUT,info.project.name+'-system.png'),fullPage:true});
  await page.getByLabel('Vehicle', { exact: true }).selectOption('bus-002');
  await page.getByRole('button', { name: 'Measurements', exact: true }).click();
  await expect(page.locator('tbody tr[data-signal]')).toHaveCount(24);
  await expect(page.locator('[data-signal="motion.speed"]')).toContainText('unknown');
  await expect(page.locator('[data-signal="motion.speed"]')).not.toContainText('fresh');
  await page.getByRole('button',{name:'Map',exact:true}).click();
  await expect(page.getByText('No published mission map is available for this vehicle.')).toBeVisible();
  await page.getByLabel('Vehicle', { exact: true }).selectOption('bus-001');
  await page.getByRole('button', { name: 'Measurements', exact: true }).click();
  await expect(page.locator('tbody tr[data-signal]')).toHaveCount(24);
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(page.locator('tbody tr[data-signal]')).toHaveCount(0);
  await page.getByLabel('Trend signal').selectOption('motion.speed');
  await expect(page.getByRole('img', { name: /Motion · Speed history/ })).toBeVisible();
  await expect(page.locator('.chart-foot')).toContainText('18 raw readings');
  await page.screenshot({ path: path.join(process.env.EVDT_BROWSER_OUTPUT, info.project.name + '-overview.png') });
  await page.screenshot({ path: path.join(process.env.EVDT_BROWSER_OUTPUT, info.project.name + '-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(process.env.EVDT_BROWSER_OUTPUT, info.project.name + '-mobile.png'), fullPage: true });
  const stored = await page.evaluate(() => ({ local: Object.keys(localStorage), session: Object.keys(sessionStorage), url: location.href }));
  expect(stored.local).toEqual([]); expect(stored.session).toEqual([]); expect(stored.url).not.toContain(fixture.reader_token);
  expect(errors).toEqual([]); expect(external).toEqual([]);
  fs.writeFileSync(path.join(control, info.project.name + '-result.json'), JSON.stringify({ passed: true, browser: browser.version(), project: info.project.name, raw_readings: 18, signals: 20, external_requests: 0, checks: ['catalog/filter', 'real history', 'disconnect/stale', 'resynchronize', 'asset isolation', 'mobile layout', 'memory-only credential','map/trajectory/layers/stations','synchronized signals','metadata JSON/CSV export','explicit summaries','activity/system views'] }));
});
