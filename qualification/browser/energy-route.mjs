import { expect } from '@playwright/test';
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';

const folder = process.argv[2];
const file = name => path.join(folder, name);
const fixture = JSON.parse(fs.readFileSync(file('browser-ready.json'), 'utf8'));
expect(fixture.monitoring_url).toBe('http://127.0.0.1:18765');
const browser = await chromium.launch({ channel: 'chromium', headless: true });
const result = { passed: false, chromium: browser.version(), checks: [] };
const stop = setInterval(() => {
  if (fs.existsSync(file('browser-stop'))) void browser.close();
}, 500);
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, serviceWorkers: 'block' });
  const errors = [];
  await context.route('**/*', route => new URL(route.request().url()).origin === fixture.monitoring_url ? route.continue() : route.abort());
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.monitoring_url);
  await page.getByLabel('Dashboard key', { exact: true }).fill(fixture.monitoring_token);
  await page.getByRole('button', { name: 'Connect to monitoring', exact: true }).click();
  await page.getByRole('button', { name: 'Energy Forecast', exact: true }).click();
  const panel = page.getByLabel('Route-aware energy forecasts', { exact: true });
  await expect(panel.getByText(/Current forecast available/)).toBeVisible({ timeout: 25000 });
  await expect(panel.getByText('Net battery energy needed', { exact: true })).toBeVisible();
  const remaining = panel.locator('.route-energy-remaining');
  await expect(remaining).toHaveCSS('background-image', /linear-gradient.*rgb\(216, 39, 125\)/);
  const charge = panel.locator('.route-energy-charge');
  await expect(charge.getByText('Measured at forecast', { exact: true })).toBeVisible();
  await expect(charge.getByText(/^Reserve \d/)).toBeVisible();
  await panel.getByText('Forecast details', { exact: true }).click();
  const coverage = panel.locator('.forecast-coverage-strip details');
  await expect(coverage.getByText(fixture.elevation_label ?? 'Declared flat', { exact: true })).toBeVisible();
  await expect(coverage.getByText('Declared calm', { exact: true })).toBeVisible();
  await panel.getByText('Forecast details', { exact: true }).click();
  await page.screenshot({ path: file('energy-current.png'), fullPage: false });
  const saved = panel.getByRole('button', { name: /^View saved forecast at/ }).first();
  await saved.click();
  await expect(panel.getByLabel('Forecast', { exact: true })).not.toHaveValue('current');
  await expect(panel.getByRole('heading', { name: 'Saved forecast', exact: true })).toBeVisible();
  await expect(panel.locator('.forecast-facts').getByText('Forecast cutoff', { exact: true })).toBeVisible();
  const selectedRow = panel.locator('tbody tr[data-selected="true"]');
  for (const series of ['measured', 'lowest', 'arrival']) {
    const bar = charge.locator(`.charge-${series} strong`);
    const cell = selectedRow.locator(`.charge-${series}`);
    await expect(bar).toHaveText(/^\d+(\.\d+)?%$/);
    await expect(cell).toHaveText(await bar.innerText());
    await expect(cell).toHaveCSS('color', await bar.evaluate(node => getComputedStyle(node).color));
  }
  await page.screenshot({ path: file('energy-saved.png'), fullPage: false });
  result.checks.push('pink_route_card_and_matching_saved_charge_values_and_colors');
  await panel.getByLabel('Forecast', { exact: true }).selectOption('current');
  await panel.getByRole('button', { name: 'Forecast vs. observed' }).click();
  await expect(panel.getByRole('heading', { name: 'Completed prediction windows' })).toBeVisible();
  await panel.getByRole('button', { name: 'Saved forecasts' }).click();
  result.checks.push('current_result_with_model_cutoff_and_energy');
  fs.writeFileSync(file('browser-connected'), '');
  await expect.poll(() => fs.existsSync(file('stale-ready')), { timeout: 30000 }).toBe(true);
  await expect(panel.getByText('Net battery energy needed', { exact: true })).toHaveCount(0, { timeout: 10000 });
  await expect(panel.getByRole('button', { name: /^View saved forecast at/ }).first()).toBeVisible();
  await page.screenshot({ path: file('energy-stale.png'), fullPage: false });
  result.checks.push('stale_current_hidden_history_retained');
  fs.writeFileSync(file('browser-stale'), '');
  await expect.poll(() => fs.existsSync(file('recovered-ready')), { timeout: 65000 }).toBe(true);
  await expect(panel.getByText(/Current forecast available/)).toBeVisible({ timeout: 15000 });
  await page.screenshot({ path: file('energy-recovered.png'), fullPage: false });
  await panel.getByRole('button',{name:'Inspect battery readings'}).click();
  await expect(page.locator('[data-history-signal]')).toHaveCount(3);
  await expect(page.locator('.history-plots .chart svg').first()).toBeVisible();
  await page.locator('.history-plots').screenshot({path:file('history-from-energy.png')});
  await page.getByRole('button',{name:'History',exact:true}).click();
  await expect(page.locator('[data-history-signal]')).toHaveCount(0);
  await page.getByRole('button',{name:'Select signals',exact:true}).click();
  const choices=page.locator('.signal-choices input[type="checkbox"]');
  await expect(choices).toHaveCount(20);
  for(const choice of await choices.all()) await choice.check();
  await expect(page.locator('[data-history-signal]')).toHaveCount(20);
  await expect(page.locator('.history-plots [aria-busy="true"]')).toHaveCount(0,{timeout:15000});
  await expect(page.locator('.history-plots [role="alert"]')).toHaveCount(0);
  await page.getByText('Select signals to compare',{exact:false}).click();
  await page.screenshot({path:file('history-all-signals.png'),fullPage:false});
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download JSON',exact:true}).click();
  const download=await downloadEvent;
  const exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
  expect(exported.metadata.batch_count).toBe(4);
  expect(exported.metadata.download_complete).toBe(true);
  expect(Object.keys(exported.metadata.signals)).toHaveLength(20);
  expect(new Set(exported.items.map(row=>row.signal_id)).size).toBe(20);
  expect(exported.metadata.row_count).toBe(exported.items.length);
  await page.getByRole('button',{name:'Calculate summary'}).click();
  await expect(page.locator('.summaries tbody tr').first()).toBeVisible();
  await expect(page.locator('.history-explorer [role="alert"]')).toHaveCount(0);
  result.checks.push('all_twenty_signal_raw_export_and_interval_summaries');
  await page.getByRole('button',{name:'Energy Forecast',exact:true}).click();
  await panel.getByRole('button',{name:/^View saved forecast at/}).first().click();
  await panel.getByRole('button',{name:'View forecast route'}).click();
  await expect(page.locator('.leaflet-container')).toBeVisible();
  await expect(page.getByRole('switch')).toHaveCount(4);
  await expect(page.locator('[data-map-layer="route"]')).toHaveCount(1);
  await page.screenshot({path:file('map-forecast.png'),fullPage:false});
  result.checks.push('energy_history_navigation_all_twenty_charts_and_bound_forecast_route');
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Trip progress' })).toBeVisible();
  await expect(page.getByLabel('Trend signal')).toBeVisible();
  await expect(page.getByLabel('History window')).toBeVisible();
  await page.screenshot({ path: file('overview-desktop.png') });
  await page.getByRole('button', { name: 'Fleet', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Vehicle comparison' })).toBeVisible();
  await expect(page.locator('[data-fleet-asset] [data-signal]')).toHaveCount(20);
  await page.screenshot({ path: file('fleet-desktop.png') });
  await page.getByRole('button', { name: 'Measurements', exact: true }).click();
  await expect(page.locator('tr[data-signal]')).toHaveCount(20);
  await page.getByLabel('Search measurements').fill('vehicle speed');
  await expect(page.locator('tr[data-signal]')).toHaveCount(1);
  await expect(page.locator('tr[data-signal]')).toHaveAttribute('data-signal', 'motion.speed');
  await page.getByLabel('Search measurements').clear();
  await page.screenshot({ path: file('measurements-desktop.png') });
  await page.getByRole('button', { name: 'Activity', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Recorded activity' })).toBeVisible();
  await page.screenshot({ path: file('activity-desktop.png') });
  await page.getByRole('button', { name: 'System', exact: true }).click();
  await expect(page.getByRole('region', { name: 'System status' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Delivery path' })).toBeVisible();
  await page.screenshot({ path: file('system-desktop.png') });
  await page.getByRole('button', { name: 'Operator', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Charging Advisor' })).toBeVisible();
  await expect(page.locator('input[type=password]')).toHaveCount(0);
  await page.screenshot({ path: file('operator-desktop.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  result.checks.push('remaining_desktop_tabs_live_at_laptop_width');
  expect(errors).toEqual([]);
  result.checks.push('recovered_after_source_outage_and_assignment_change');
  result.passed = true;
} catch (error) {
  result.error = String(error);
  process.exitCode = 1;
} finally {
  clearInterval(stop);
  await browser.close();
  fs.writeFileSync(file('browser-result.json'), JSON.stringify(result, null, 2));
}
