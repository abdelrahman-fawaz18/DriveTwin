import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
const control = process.env.EVDT_DASHBOARD_CONTROL;
const fixture = JSON.parse(fs.readFileSync(path.join(control, 'ready.json'), 'utf8'));
test('actual energy view, original history, stale suppression and asset switching', async ({ page, request }) => {
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.goto('/');
  await page.getByLabel('Dashboard key').fill(fixture.token);
  await page.getByRole('button', { name: 'Connect to monitoring' }).click();
  await page.getByRole('button', { name: 'Energy', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Current forecast', exact: true })).toBeVisible();
  fs.writeFileSync(path.join(control, 'ready'), 'ready');
  await expect(page.getByTestId('energy-estimate')).toBeVisible({ timeout: 45_000 });
  await expect(page.getByText('Advisory forecast available', { exact: true })).toBeVisible();
  await expect(page.getByText('Scenario ranges have no probability guarantee.')).toBeVisible();
  const response = await request.get('/v1/energy-forecasts?asset_id=bus-001', { headers: { Authorization: `Bearer ${fixture.token}` } });
  expect(response.status()).toBe(200);
  const view = await response.json();
  expect(view.status).toBe('advisory');
  const rendered = Number((await page.getByTestId('energy-estimate').innerText()).replaceAll(',', '').replace(' kWh', ''));
  expect(Math.abs(rendered - view.values.net_mission_energy_kwh)).toBeLessThanOrEqual(0.0005);
  await expect(page.getByRole('img', { name: /^Estimated final charge/ })).toBeVisible();
  await expect(page.getByTestId('forecast-horizon')).toContainText('min');
  await expect(page.getByTestId('forecast-assumptions')).toContainText('350 kWh');
  await expect(page.getByRole('table', { name: 'Station assessments' }).locator('tbody tr')).toHaveCount(2);
  fs.writeFileSync(path.join(control, 'available-seen'), 'seen');
  await page.screenshot({ path: path.join(process.env.EVDT_BROWSER_OUTPUT, 'available.png'), fullPage: true });
  await expect(page.getByTestId('energy-estimate')).toHaveCount(0, { timeout: 12_000 });
  await expect(page.locator('.forecast-history tbody tr')).toHaveCount(1);
  await expect(page.locator('.forecast-history tbody')).toContainText('advisory');
  fs.writeFileSync(path.join(control, 'stale-seen'), 'seen');
  // Network loss must not leave a fresh card on-screen. Original saved history remains labeled.
  await page.route('**/v1/energy-forecasts?*', route => route.abort());
  await expect(page.getByText('Forecast connection unavailable. Saved history may be out of date.')).toBeVisible();
  await expect(page.getByTestId('energy-estimate')).toHaveCount(0);
  await page.screenshot({ path: path.join(process.env.EVDT_BROWSER_OUTPUT, 'disconnected.png'), fullPage: true });
  await page.unroute('**/v1/energy-forecasts?*');
  await expect(page.getByText('Forecast connection unavailable. Saved history may be out of date.')).toHaveCount(0);
  await page.getByLabel('Vehicle', { exact: true }).selectOption('bus-002');
  await expect(page.getByText('No saved forecasts for this vehicle.')).toBeVisible();
  await expect(page.locator('.forecast-history tbody tr')).toHaveCount(0);
  await page.getByLabel('Vehicle', { exact: true }).selectOption('bus-001');
  await expect(page.locator('.forecast-history tbody tr')).toHaveCount(1);
  await page.screenshot({ path: path.join(process.env.EVDT_BROWSER_OUTPUT, 'stale.png'), fullPage: true });
  expect(errors).toEqual([]);
  fs.writeFileSync(path.join(process.env.EVDT_BROWSER_OUTPUT, 'result.json'), JSON.stringify({ passed: true, current_advisory_seen: true, displayed_value_matches_service: true, endpoint_chart_and_two_station_assessments: true, stale_values_hidden: true, immutable_history_visible: true, disconnected_values_hidden: true, connection_recovered: true, asset_switch_cleared_old_state: true, page_errors: 0 }));
});
